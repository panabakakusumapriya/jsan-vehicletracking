/** [lon, lat] rings. Water cut out of the land above. */
const HOLES = [
  [[28, 41], [41, 41], [41, 46.5], [30, 46.5]], // Black Sea
  [[47, 37], [54, 37], [54, 47], [47, 47]], // Caspian Sea
];

function inside(ring, lon, lat) {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

const bytes = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let land = 0;
const preview = [];
for (let r = 0; r < ROWS; r++) {
  let line = '';
  for (let c = 0; c < COLS; c++) {
    const lat = LAT_TOP - (r + 0.5) * STEP;
    const lon = -180 + (c + 0.5) * STEP;
    const isLand = LAND.some((ring) => inside(ring, lon, lat)) && !HOLES.some((ring) => inside(ring, lon, lat));
    if (isLand) {
      const i = r * COLS + c;
      bytes[i >> 3] |= 1 << (i & 7);
      land++;
    }
    line += isLand ? '#' : '.';
  }
  preview.push(line);
}

const out = `// Generated by scripts/generate-world-land.mjs — do not edit by hand.
// One bit per ${STEP}° cell, row-major from ${LAT_TOP}°N down to ${LAT_BOTTOM}°S and from 180°W eastward;
// a set bit is land. ${land} land cells of ${COLS * ROWS}.
export const WORLD_LAND = {
  cols: ${COLS},
  rows: ${ROWS},
  step: ${STEP},
  latTop: ${LAT_TOP},
  bits: '${Buffer.from(bytes).toString('base64')}',
} as const;
`;
writeFileSync(path.join(here, '..', 'src', 'components', 'worldLand.ts'), out);
console.log(preview.join('\n'));
