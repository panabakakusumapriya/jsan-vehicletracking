import { useEffect, useRef } from 'react';
import { WORLD_LAND } from './worldLand';

/**
 * The login panel's backdrop: the world as a dot-matrix of blue points on white, with deeper blue
 * routes arcing between places on it. Each route is a trip: a tracked unit sets off from one hub, the arc lights
 * up in blue behind it as it travels (the Coverage page's "driven" colour), and a GPS ping rings
 * out where it arrives; the finished route lingers, fades, and another begins somewhere else. The
 * hubs pulse softly, the dots shimmer in a slow wave, the camera drifts, and points near the
 * pointer brighten to blue.
 *
 * Blue on white only. Canvas 2D in one requestAnimationFrame loop; the land dots come from
 * worldLand.ts (2° cells, generated by scripts/generate-world-land.mjs), fitted to the panel's
 * width. Motion is integrated per second, so it runs at the same pace on 60 Hz and 120 Hz screens,
 * and pauses while the tab is hidden. With reduced motion asked for, one still frame is drawn and
 * nothing moves. Decorative only; it carries no data — the hubs are unlabelled world cities.
 */

type Trip = { a: number; b: number; t: number; dur: number; doneAt: number };
type Ring = { x: number; y: number; born: number };

const WHITE = '255, 255, 255'; // the core of a tracked unit
const DOT_BLUE = '125, 184, 232'; // --brand-2: the land
const ROUTE_BLUE = '0, 80, 169'; // --brand: a route drawn but not yet driven, and the hubs
const DRIVEN_BLUE = '0, 80, 169'; // the travelled part of a route, and the unit's ring
const ACCENT_BLUE = '59, 142, 232'; // pings

/** [lon, lat] of the places routes run between. Spread across every continent; never labelled. */
const HUBS: Array<[number, number]> = [
  [151.2, -33.9], [174.8, -36.9], [115.9, -31.9], [103.8, 1.3], [139.7, 35.7], [116.4, 39.9], [78.5, 17.4],
  [72.9, 19.1], [55.3, 25.2], [37.6, 55.8], [28.0, -26.2], [36.8, -1.3], [3.4, 6.5], [31.2, 30.0], [-0.1, 51.5],
  [8.7, 50.1], [-3.7, 40.4], [-74.0, 40.7], [-87.6, 41.9], [-118.2, 34.1], [-99.1, 19.4], [-46.6, -23.5],
  [-58.4, -34.6], [-79.4, 43.7], [-123.1, 49.3], [106.8, -6.2],
];

const MAX_TRIPS = 6;
const UNIT_PX_PER_S = 150; // how fast a tracked unit moves along its arc
const LINGER_S = 2.4; // a finished route stays lit this long before fading out
const FADE_S = 1.6;
const PING_LIFE_S = 1.8;
const POINTER_RANGE = 120;
const MAP_WIDTH_SHARE = 1.12; // the map is a little wider than the panel, so its edges run off

/** Land cells as [col, row] pairs. */
function decodeLand(): Array<[number, number]> {
  const bytes = Uint8Array.from(atob(WORLD_LAND.bits), (ch) => ch.charCodeAt(0));
  const cells: Array<[number, number]> = [];
  const total = WORLD_LAND.cols * WORLD_LAND.rows;
  for (let i = 0; i < total; i++) {
    if (bytes[i >> 3] & (1 << (i & 7))) cells.push([i % WORLD_LAND.cols, Math.floor(i / WORLD_LAND.cols)]);
  }
  return cells;
}

export function FleetField({ className }: { className?: string }) {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    const host = canvas?.parentElement;
    if (!canvas || !host) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    const still = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches ?? false;
    const land = decodeLand();
    const latSpan = WORLD_LAND.rows * WORLD_LAND.step;

    let w = 0;
    let h = 0;
    let dpr = 1;
    // Projection (equirectangular): screen = origin + degrees * scale.
    let scale = 1;
    let x0 = 0;
    let y0 = 0;
    let dotR = 1.5;
    const dotX = new Float32Array(land.length);
    const dotY = new Float32Array(land.length);
    const hubX = new Float32Array(HUBS.length);
    const hubY = new Float32Array(HUBS.length);
    let trips: Trip[] = [];
    let rings: Ring[] = [];
    const pointer = { x: 0, y: 0, on: false };
    let raf = 0;
    let last = 0;
    let disposed = false;

    const project = (lon: number, lat: number): [number, number] => [x0 + (lon + 180) * scale, y0 + (WORLD_LAND.latTop - lat) * scale];

    function layout() {
      scale = (w * MAP_WIDTH_SHARE) / 360;
      x0 = (w - 360 * scale) / 2;
      y0 = (h - latSpan * scale) / 2;
      dotR = Math.max(1.1, WORLD_LAND.step * scale * 0.27);
      land.forEach(([c, r], i) => {
        const [x, y] = project(-180 + (c + 0.5) * WORLD_LAND.step, WORLD_LAND.latTop - (r + 0.5) * WORLD_LAND.step);
        dotX[i] = x;
        dotY[i] = y;
      });
      HUBS.forEach(([lon, lat], i) => {
        const [x, y] = project(lon, lat);
        hubX[i] = x;
        hubY[i] = y;
      });
    }

    /** The arc from hub a to hub b: a quadratic curve bowing towards the top of the map. */
    function arc(a: number, b: number) {
      const ax = hubX[a]; const ay = hubY[a]; const bx = hubX[b]; const by = hubY[b];
      const dx = bx - ax; const dy = by - ay;
      const len = Math.hypot(dx, dy) || 1;
      let nx = -dy / len; let ny = dx / len;
      if (ny > 0) { nx = -nx; ny = -ny; }
      const lift = len * 0.22;
      return { ax, ay, cx: (ax + bx) / 2 + nx * lift, cy: (ay + by) / 2 + ny * lift, bx, by, len };
    }

    function startTrip(now: number) {
      const busy = new Set(trips.flatMap((t) => [t.a, t.b]));
      for (let tries = 0; tries < 40; tries++) {
        const a = Math.floor(Math.random() * HUBS.length);
        const b = Math.floor(Math.random() * HUBS.length);
        if (a === b || busy.has(a) || busy.has(b)) continue;
        const dLon = Math.abs(HUBS[a][0] - HUBS[b][0]);
        const dLat = Math.abs(HUBS[a][1] - HUBS[b][1]);
        if (Math.hypot(Math.min(dLon, 360 - dLon), dLat) < 18 || dLon > 170) continue; // too short, or across the seam
        trips.push({ a, b, t: 0, dur: Math.max(2.5, arc(a, b).len / UNIT_PX_PER_S), doneAt: 0 });
        return;
      }
      void now;
    }

    function resize() {
      const rect = host!.getBoundingClientRect();
      w = Math.max(1, Math.round(rect.width));
      h = Math.max(1, Math.round(rect.height));
      dpr = Math.min(2, window.devicePixelRatio || 1);
      canvas!.width = Math.round(w * dpr);
      canvas!.height = Math.round(h * dpr);
      canvas!.style.width = `${w}px`;
      canvas!.style.height = `${h}px`;
      layout();
      if (still) {
        // One frame: routes part-way through their trips, so the picture reads at a glance.
        trips = [];
        for (let i = 0; i < MAX_TRIPS; i++) startTrip(0);
        trips.forEach((t, i) => { t.t = 0.45 + (i / MAX_TRIPS) * 0.5; });
        draw(performance.now());
      }
    }

    function step(dt: number, now: number) {
      for (const t of trips) {
        if (t.doneAt) continue;
        t.t = Math.min(1, t.t + dt / t.dur);
        if (t.t >= 1) {
          t.doneAt = now;
          rings.push({ x: hubX[t.b], y: hubY[t.b], born: now });
        }
      }
      trips = trips.filter((t) => !t.doneAt || now - t.doneAt < (LINGER_S + FADE_S) * 1000);
      rings = rings.filter((r) => now - r.born < PING_LIFE_S * 1000);
      // New trips start one at a time, so departures are spread out rather than in a burst.
      if (trips.length < MAX_TRIPS && Math.random() < dt * 0.9) startTrip(now);
    }

    /** The slow camera: a gentle zoom in and out with a little sideways drift. */
    function view(now: number) {
      if (still) return { k: 1, px: 0, py: 0 };
      return {
        k: 1 + 0.04 * (0.5 - 0.5 * Math.cos((now / 34000) * Math.PI * 2)),
        px: 12 * Math.sin((now / 25000) * Math.PI * 2),
        py: 8 * Math.cos((now / 21000) * Math.PI * 2),
      };
    }

    function draw(now: number) {
      const g = ctx!;
      g.setTransform(dpr, 0, 0, dpr, 0, 0);
      g.clearRect(0, 0, w, h);
      // screen = k * (world - w/2 + px) + w/2
      const { k, px, py } = view(now);
      g.setTransform(dpr * k, 0, 0, dpr * k, dpr * (w / 2 - k * (w / 2 - px)), dpr * (h / 2 - k * (h / 2 - py)));
      g.lineCap = 'round';
      g.lineJoin = 'round';

      // The land, as blue dots. A slow wave of brightness crosses it west to east; dots near the
      // pointer are drawn afterwards in the deeper blue.
      const wx = (pointer.x - w / 2) / k + w / 2 - px;
      const wy = (pointer.y - h / 2) / k + h / 2 - py;
      const lit: number[] = [];
      const TAU = Math.PI * 2;
      const byCol: number[][] = Array.from({ length: WORLD_LAND.cols }, () => []);
      for (let i = 0; i < land.length; i++) {
        if (pointer.on && Math.hypot(dotX[i] - wx, dotY[i] - wy) < POINTER_RANGE) { lit.push(i); continue; }
        byCol[land[i][0]].push(i);
      }
      for (let c = 0; c < byCol.length; c++) {
        const idx = byCol[c];
        if (!idx.length) continue;
        const shimmer = still ? 0.5 : 0.5 + 0.5 * Math.sin(c * 0.11 - (now / 1700) * TAU * 0.25);
        g.fillStyle = `rgba(${DOT_BLUE}, ${(0.42 + shimmer * 0.3).toFixed(3)})`;
        g.beginPath();
        for (const i of idx) {
          g.moveTo(dotX[i] + dotR, dotY[i]);
          g.arc(dotX[i], dotY[i], dotR, 0, TAU);
        }
        g.fill();
      }
      if (lit.length) {
        g.beginPath();
        for (const i of lit) {
          g.moveTo(dotX[i] + dotR * 1.35, dotY[i]);
          g.arc(dotX[i], dotY[i], dotR * 1.35, 0, TAU);
        }
        g.fillStyle = `rgba(${ROUTE_BLUE}, 0.95)`;
        g.fill();
      }

      // Routes: the whole arc faint, the part already travelled bright and glowing; a finished
      // trip lingers, then fades.
      for (const t of trips) {
        const age = t.doneAt ? (now - t.doneAt) / 1000 : 0;
        const alpha = age > LINGER_S ? Math.max(0, 1 - (age - LINGER_S) / FADE_S) : 1;
        if (alpha <= 0) continue;
        const { ax, ay, cx, cy, bx, by } = arc(t.a, t.b);
        g.beginPath(); g.moveTo(ax, ay); g.quadraticCurveTo(cx, cy, bx, by);
        g.lineWidth = 1; g.strokeStyle = `rgba(${ROUTE_BLUE}, ${(0.22 * alpha).toFixed(3)})`; g.stroke();

        // The travelled part: split the curve at t (de Casteljau).
        const s = t.t;
        const qx = ax + (cx - ax) * s; const qy = ay + (cy - ay) * s;
        const rx = cx + (bx - cx) * s; const ry = cy + (by - cy) * s;
        const hx = qx + (rx - qx) * s; const hy = qy + (ry - qy) * s;
        g.beginPath(); g.moveTo(ax, ay); g.quadraticCurveTo(qx, qy, hx, hy);
        g.lineWidth = 6; g.strokeStyle = `rgba(${DRIVEN_BLUE}, ${(0.12 * alpha).toFixed(3)})`; g.stroke();
        g.lineWidth = 2; g.strokeStyle = `rgba(${DRIVEN_BLUE}, ${(0.9 * alpha).toFixed(3)})`; g.stroke();

        // The tracked unit: a white dot in a blue ring, in a soft halo, at the head of the route.
        if (!t.doneAt) {
          g.beginPath(); g.arc(hx, hy, 10, 0, TAU); g.fillStyle = `rgba(${DRIVEN_BLUE}, 0.16)`; g.fill();
          g.beginPath(); g.arc(hx, hy, 3.4, 0, TAU); g.fillStyle = `rgb(${WHITE})`; g.fill();
          g.lineWidth = 2; g.strokeStyle = `rgb(${DRIVEN_BLUE})`; g.stroke();
        }
      }

      // GPS pings: a ring that grows and fades where a unit reported in.
      g.lineWidth = 1.5;
      for (const r of rings) {
        const p = (now - r.born) / (PING_LIFE_S * 1000);
        g.strokeStyle = `rgba(${ACCENT_BLUE}, ${((1 - p) * 0.6).toFixed(3)})`;
        g.beginPath(); g.arc(r.x, r.y, 5 + 40 * p, 0, TAU); g.stroke();
      }

      // Hubs: small blue points with a softly breathing halo.
      for (let i = 0; i < HUBS.length; i++) {
        const pulse = still ? 0.5 : 0.5 + 0.5 * Math.sin((now / 2600) * TAU + i * 1.7);
        g.beginPath(); g.arc(hubX[i], hubY[i], 5 + pulse * 3, 0, TAU);
        g.fillStyle = `rgba(${ROUTE_BLUE}, ${(0.08 + pulse * 0.12).toFixed(3)})`; g.fill();
        g.beginPath(); g.arc(hubX[i], hubY[i], 2.4, 0, TAU);
        g.fillStyle = `rgba(${ROUTE_BLUE}, 0.9)`; g.fill();
      }
    }

    function frame(now: number) {
      if (disposed) return;
      const dt = Math.min(0.05, last ? (now - last) / 1000 : 0);
      last = now;
      step(dt, now);
      draw(now);
      raf = requestAnimationFrame(frame);
    }

    const onMove = (e: PointerEvent) => {
      const r = canvas!.getBoundingClientRect();
      pointer.x = e.clientX - r.left;
      pointer.y = e.clientY - r.top;
      pointer.on = true;
    };
    const onLeave = () => { pointer.on = false; };
    const onVisibility = () => {
      if (document.hidden) { cancelAnimationFrame(raf); raf = 0; }
      else if (!raf) { last = 0; raf = requestAnimationFrame(frame); }
    };

    const ro = new ResizeObserver(resize);
    ro.observe(host);
    resize();
    if (!still) {
      // Open with a few trips already under way rather than an empty map.
      for (let i = 0; i < 3; i++) startTrip(0);
      trips.forEach((t, i) => { t.t = (i + 1) * 0.22; });
      host.addEventListener('pointermove', onMove);
      host.addEventListener('pointerleave', onLeave);
      document.addEventListener('visibilitychange', onVisibility);
      raf = requestAnimationFrame(frame);
    }
    return () => {
      disposed = true;
      cancelAnimationFrame(raf);
      ro.disconnect();
      host.removeEventListener('pointermove', onMove);
      host.removeEventListener('pointerleave', onLeave);
      document.removeEventListener('visibilitychange', onVisibility);
    };
  }, []);

  return <canvas ref={canvasRef} className={className} aria-hidden="true" />;
}
