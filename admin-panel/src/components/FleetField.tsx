/**
 * The login panel's backdrop: the world as a dot-matrix of blue points on white, with a faint road
 * network laid over the land, town to town inside each state and country. Cars drive it: each one
 * sets off from a town, follows the roads through a few towns, and the road it has covered lights
 * up in blue behind it (the Coverage page's "driven" colour). A GPS ping rings out at every town it
 * passes; at journey's end the trail lingers, fades, and another car sets off somewhere else. Cars
 * never leave the land: there are no routes across the sea. The dots shimmer in a slow wave, the
 * camera drifts, and points near the pointer brighten to blue.
 *
 * Blue on white only. Canvas 2D in one requestAnimationFrame loop; the land dots come from
 * worldLand.ts (2° cells, generated by scripts/generate-world-land.mjs), fitted to the panel's
 * width. Motion is integrated per second, so it runs at the same pace on 60 Hz and 120 Hz screens,
 * and pauses while the tab is hidden. With reduced motion asked for, one still frame is drawn and
 * nothing moves. Decorative only; it carries no data — the towns are never labelled.
 */

