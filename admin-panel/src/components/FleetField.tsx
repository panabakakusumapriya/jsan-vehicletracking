const TOWN_NAMES = Object.keys(TOWNS);
const TOWN_POS = TOWN_NAMES.map((n) => TOWNS[n]);

/** Stable pseudo-random in [0, 1) for a seed, so every road bends the same way on every load. */
const hash = (n: number) => { const s = Math.sin(n * 127.1 + 311.7) * 43758.5453; return s - Math.floor(s); };

/** Road links between neighbouring towns, each with a gently bent shape in [lon, lat]. */
const EDGES: Array<{ a: number; b: number; shape: Array<[number, number]> }> = [];
const NEIGHBOURS: number[][] = TOWN_NAMES.map(() => []);
const EDGE_OF = new Map<string, number>();
for (const road of ROADS) {
  for (let i = 1; i < road.length; i++) {
    const a = TOWN_NAMES.indexOf(road[i - 1]);
    const b = TOWN_NAMES.indexOf(road[i]);
    if (a < 0 || b < 0 || EDGE_OF.has(`${a}-${b}`)) continue;
    const [ax, ay] = TOWN_POS[a];
    const [bx, by] = TOWN_POS[b];
    const dx = bx - ax; const dy = by - ay;
    const len = Math.hypot(dx, dy) || 1;
    const nx = -dy / len; const ny = dx / len;
    const e = EDGES.length;
    const shape: Array<[number, number]> = [[ax, ay]];
    // Two bends, opposite ways, so a link reads as a road rather than a ruled line.
    for (const [f, side] of [[1 / 3, 1], [2 / 3, -1]] as const) {
      const o = side * len * (0.04 + 0.07 * hash(e * 2 + f * 3));
      shape.push([ax + dx * f + nx * o, ay + dy * f + ny * o]);
    }
    shape.push([bx, by]);
    EDGES.push({ a, b, shape });
    EDGE_OF.set(`${a}-${b}`, e);
    EDGE_OF.set(`${b}-${a}`, e);
    NEIGHBOURS[a].push(b);
    NEIGHBOURS[b].push(a);
  }
}

const MAX_CARS = 9;
const CAR_PX_PER_S = 30; // how fast a car drives along the road
const LINGER_S = 2.4; // a finished journey stays lit this long before fading out
const FADE_S = 1.6;
const PING_LIFE_S = 1.6;
const POINTER_RANGE = 120;
const MAP_WIDTH_SHARE = 1.12; // the map is a little wider than the panel, so its edges run off

/** Land cells as [col, row] pairs. */
function decodeLand(): Array<[number, number]> {
  const bytes = Uint8Array.from(atob(WORLD_LAND.bits), (ch) => ch.charCodeAt(0));
  const cells: Array<[number, number]> = [];
  const total = WORLD_LAND.cols * WORLD_LAND.rows;
  for (let i = 0; i < total; i++) {
    if (bytes[i >> 3] & (1 << (i & 7))) cells.push([i % WORLD_LAND.cols, Math.floor(i / WORLD_LAND.cols)]);
  }
  return cells;
}

export function FleetField({ className }: { className?: string }) {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    const host = canvas?.parentElement;
    if (!canvas || !host) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    const still = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches ?? false;
    const land = decodeLand();
    const latSpan = WORLD_LAND.rows * WORLD_LAND.step;

    let w = 0;
    let h = 0;
    let dpr = 1;
    // Projection (equirectangular): screen = origin + degrees * scale.
    let scale = 1;
    let x0 = 0;
    let y0 = 0;
    let dotR = 1.5;
    let ver = 0; // bumped on every layout, so cars rebuild their screen lines
    const dotX = new Float32Array(land.length);
    const dotY = new Float32Array(land.length);
    const townX = new Float32Array(TOWN_POS.length);
    const townY = new Float32Array(TOWN_POS.length);
    let network = new Path2D();
    let cars: Car[] = [];
    let rings: Ring[] = [];
    const pointer = { x: 0, y: 0, on: false };
    let raf = 0;
    let last = 0;
    let disposed = false;

    const project = (lon: number, lat: number): [number, number] => [x0 + (lon + 180) * scale, y0 + (WORLD_LAND.latTop - lat) * scale];

    function layout() {
      scale = (w * MAP_WIDTH_SHARE) / 360;
      x0 = (w - 360 * scale) / 2;
      y0 = (h - latSpan * scale) / 2;
      dotR = Math.max(1.1, WORLD_LAND.step * scale * 0.27);
      land.forEach(([c, r], i) => {
        const [x, y] = project(-180 + (c + 0.5) * WORLD_LAND.step, WORLD_LAND.latTop - (r + 0.5) * WORLD_LAND.step);
        dotX[i] = x;
        dotY[i] = y;
      });
      TOWN_POS.forEach(([lon, lat], i) => {
        const [x, y] = project(lon, lat);
        townX[i] = x;
        townY[i] = y;
      });
      network = new Path2D();
      for (const { shape } of EDGES) {
        shape.forEach(([lon, lat], i) => {
          const [x, y] = project(lon, lat);
          if (i) network.lineTo(x, y); else network.moveTo(x, y);
        });
      }
      ver++;
    }

    /** A route's road in screen space, with the distance along it at which each town is reached. */
    function lineOf(route: number[]): Line {
      const pts: Array<[number, number]> = [];
      const townAt: number[] = [];
      for (let i = 1; i < route.length; i++) {
        const e = EDGES[EDGE_OF.get(`${route[i - 1]}-${route[i]}`)!];
        const shape = e.a === route[i - 1] ? e.shape : [...e.shape].reverse();
        // Each link starts where the last one ended, so only the first link keeps its first point.
        shape.forEach(([lon, lat], j) => { if (j || i === 1) pts.push(project(lon, lat)); });
        townAt.push(pts.length - 1);
      }
      const x = new Float32Array(pts.length);
      const y = new Float32Array(pts.length);
      const cum = new Float32Array(pts.length);
      pts.forEach(([px, py], i) => {
        x[i] = px; y[i] = py;
        if (i) cum[i] = cum[i - 1] + Math.hypot(px - x[i - 1], py - y[i - 1]);
      });
      return { x, y, cum, len: cum[pts.length - 1], towns: townAt.map((i) => cum[i]) };
    }

    const lineFor = (car: Car) => {
      if (!car.line || car.ver !== ver) { car.line = lineOf(car.route); car.ver = ver; }
      return car.line;
    };

    /** Plan a journey: from a free town, along the roads through a few towns, never doubling back. */
    function startCar() {
      const busy = new Set(cars.flatMap((c) => [c.route[0], c.route[c.route.length - 1]]));
      for (let tries = 0; tries < 40; tries++) {
        const start = Math.floor(Math.random() * TOWN_POS.length);
        if (busy.has(start) || !NEIGHBOURS[start].length) continue;
        const route = [start];
        const legs = 2 + Math.floor(Math.random() * 4);
        while (route.length <= legs) {
          const here = route[route.length - 1];
          const next = NEIGHBOURS[here].filter((n) => !route.includes(n));
          if (!next.length) break;
          route.push(next[Math.floor(Math.random() * next.length)]);
        }
        if (route.length < 2 || busy.has(route[route.length - 1])) continue;
        const car: Car = { route, line: null, ver: -1, d: 0, nextTown: 0, doneAt: 0 };
        if (lineFor(car).len < 24) continue; // too short to read as a drive at this size
        cars.push(car);
        return car;
      }
      return null;
    }

    /** Where a car is at distance d: the point, its heading, and the last road point behind it. */
    function at(line: Line, d: number) {
      let i = 1;
      while (i < line.cum.length - 1 && line.cum[i] < d) i++;
      const seg = line.cum[i] - line.cum[i - 1] || 1;
      const f = Math.min(1, Math.max(0, (d - line.cum[i - 1]) / seg));
      const dx = line.x[i] - line.x[i - 1];
      const dy = line.y[i] - line.y[i - 1];
      return { x: line.x[i - 1] + dx * f, y: line.y[i - 1] + dy * f, heading: Math.atan2(dy, dx), behind: i - 1 };
    }

    /** Put a new car part-way along its journey, as if it had set off a while ago. */
    function partWay(car: Car, share: number) {
      const line = lineFor(car);
      car.d = line.len * share;
      car.nextTown = line.towns.filter((t) => t < car.d).length;
    }

    function resize() {
      const rect = host!.getBoundingClientRect();
      w = Math.max(1, Math.round(rect.width));
      h = Math.max(1, Math.round(rect.height));
      dpr = Math.min(2, window.devicePixelRatio || 1);
      canvas!.width = Math.round(w * dpr);
      canvas!.height = Math.round(h * dpr);
      canvas!.style.width = `${w}px`;
      canvas!.style.height = `${h}px`;
      layout();
      if (still) {
        // One frame: cars part-way through their journeys, so the picture reads at a glance.
        cars = [];
        for (let i = 0; i < MAX_CARS; i++) {
          const car = startCar();
          if (car) partWay(car, 0.35 + (i / MAX_CARS) * 0.5);
        }
        draw(performance.now());
      }
    }

    function step(dt: number, now: number) {
      for (const c of cars) {
        if (c.doneAt) continue;
        const line = lineFor(c);
        c.d = Math.min(line.len, c.d + dt * CAR_PX_PER_S);
        // A ping at every town passed; the last one marks the journey's end.
        while (c.nextTown < line.towns.length && c.d >= line.towns[c.nextTown] - 0.01) {
          const town = c.route[c.nextTown + 1];
          const end = c.nextTown === line.towns.length - 1;
          rings.push({ x: townX[town], y: townY[town], born: now, big: end });
          c.nextTown++;
          if (end) c.doneAt = now;
        }
      }
      cars = cars.filter((c) => !c.doneAt || now - c.doneAt < (LINGER_S + FADE_S) * 1000);
      rings = rings.filter((r) => now - r.born < PING_LIFE_S * 1000);
      // New cars set off one at a time, so departures are spread out rather than in a burst.
      if (cars.length < MAX_CARS && Math.random() < dt * 0.9) startCar();
    }

    /** The slow camera: a gentle zoom in and out with a little sideways drift. */
    function view(now: number) {
      if (still) return { k: 1, px: 0, py: 0 };
      return {
        k: 1 + 0.04 * (0.5 - 0.5 * Math.cos((now / 34000) * Math.PI * 2)),
        px: 12 * Math.sin((now / 25000) * Math.PI * 2),
        py: 8 * Math.cos((now / 21000) * Math.PI * 2),
      };
    }

    /** A car seen from above, nose along its heading: white body, blue outline and windscreen, headlights ahead. */
    function drawCar(g: CanvasRenderingContext2D, x: number, y: number, heading: number) {
      g.beginPath(); g.arc(x, y, 11, 0, Math.PI * 2); g.fillStyle = `rgba(${DRIVEN_BLUE}, 0.14)`; g.fill();
      g.save();
      g.translate(x, y);
      g.rotate(heading);
      g.beginPath(); g.moveTo(6, -1.6); g.lineTo(17, -5.5); g.lineTo(17, 5.5); g.lineTo(6, 1.6); g.closePath();
      g.fillStyle = `rgba(${ACCENT_BLUE}, 0.16)`; g.fill();
      const L = 6; const W = 3.4; const r = 1.8;
      g.beginPath();
      g.moveTo(-L + r, -W); g.lineTo(L - r, -W); g.arcTo(L, -W, L, -W + r, r); g.lineTo(L, W - r); g.arcTo(L, W, L - r, W, r);
      g.lineTo(-L + r, W); g.arcTo(-L, W, -L, W - r, r); g.lineTo(-L, -W + r); g.arcTo(-L, -W, -L + r, -W, r); g.closePath();
      g.fillStyle = `rgb(${WHITE})`; g.fill();
      g.lineWidth = 1.6; g.strokeStyle = `rgb(${DRIVEN_BLUE})`; g.stroke();
      g.fillStyle = `rgba(${DRIVEN_BLUE}, 0.9)`;
      g.fillRect(1.4, -2.3, 1.8, 4.6);
      g.restore();
    }

    function draw(now: number) {
      const g = ctx!;
      g.setTransform(dpr, 0, 0, dpr, 0, 0);
      g.clearRect(0, 0, w, h);
      // screen = k * (world - w/2 + px) + w/2
      const { k, px, py } = view(now);
      g.setTransform(dpr * k, 0, 0, dpr * k, dpr * (w / 2 - k * (w / 2 - px)), dpr * (h / 2 - k * (h / 2 - py)));
      g.lineCap = 'round';
      g.lineJoin = 'round';

      // The land, as blue dots. A slow wave of brightness crosses it west to east; dots near the
      // pointer are drawn afterwards in the deeper blue.
      const wx = (pointer.x - w / 2) / k + w / 2 - px;
      const wy = (pointer.y - h / 2) / k + h / 2 - py;
      const lit: number[] = [];
      const TAU = Math.PI * 2;
      const byCol: number[][] = Array.from({ length: WORLD_LAND.cols }, () => []);
      for (let i = 0; i < land.length; i++) {
        if (pointer.on && Math.hypot(dotX[i] - wx, dotY[i] - wy) < POINTER_RANGE) { lit.push(i); continue; }
        byCol[land[i][0]].push(i);
      }
      for (let c = 0; c < byCol.length; c++) {
        const idx = byCol[c];
        if (!idx.length) continue;
        const shimmer = still ? 0.5 : 0.5 + 0.5 * Math.sin(c * 0.11 - (now / 1700) * TAU * 0.25);
        g.fillStyle = `rgba(${DOT_BLUE}, ${(0.42 + shimmer * 0.3).toFixed(3)})`;
        g.beginPath();
        for (const i of idx) {
          g.moveTo(dotX[i] + dotR, dotY[i]);
          g.arc(dotX[i], dotY[i], dotR, 0, TAU);
        }
        g.fill();
      }
      if (lit.length) {
        g.beginPath();
        for (const i of lit) {
          g.moveTo(dotX[i] + dotR * 1.35, dotY[i]);
          g.arc(dotX[i], dotY[i], dotR * 1.35, 0, TAU);
        }
        g.fillStyle = `rgba(${ROAD_BLUE}, 0.95)`;
        g.fill();
      }

      // The road network, faint, and the towns on it as small points.
      g.lineWidth = 1; g.strokeStyle = `rgba(${ROAD_BLUE}, 0.2)`; g.stroke(network);
      g.beginPath();
      for (let i = 0; i < TOWN_POS.length; i++) {
        if (!NEIGHBOURS[i].length) continue;
        g.moveTo(townX[i] + 1.7, townY[i]);
        g.arc(townX[i], townY[i], 1.7, 0, TAU);
      }
      g.fillStyle = `rgba(${ROAD_BLUE}, 0.55)`; g.fill();

      // Journeys: the road ahead a little stronger than the network, the road covered bright and
      // glowing; a finished journey lingers, then fades.
      for (const c of cars) {
        const age = c.doneAt ? (now - c.doneAt) / 1000 : 0;
        const alpha = age > LINGER_S ? Math.max(0, 1 - (age - LINGER_S) / FADE_S) : 1;
        if (alpha <= 0) continue;
        const line = lineFor(c);
        const pos = at(line, c.d);
        if (!c.doneAt) {
          g.beginPath(); g.moveTo(pos.x, pos.y);
          for (let i = pos.behind + 1; i < line.x.length; i++) g.lineTo(line.x[i], line.y[i]);
          g.lineWidth = 1.2; g.strokeStyle = `rgba(${ROAD_BLUE}, 0.32)`; g.stroke();
          // The destination breathes, so you can see where the car is headed.
          const dest = c.route[c.route.length - 1];
          const pulse = still ? 0.5 : 0.5 + 0.5 * Math.sin((now / 1300) * TAU);
          g.beginPath(); g.arc(townX[dest], townY[dest], 4 + pulse * 3, 0, TAU);
          g.fillStyle = `rgba(${ROAD_BLUE}, ${(0.1 + pulse * 0.12).toFixed(3)})`; g.fill();
        }
        g.beginPath(); g.moveTo(line.x[0], line.y[0]);
        for (let i = 1; i <= pos.behind; i++) g.lineTo(line.x[i], line.y[i]);
        g.lineTo(pos.x, pos.y);
        g.lineWidth = 6; g.strokeStyle = `rgba(${DRIVEN_BLUE}, ${(0.12 * alpha).toFixed(3)})`; g.stroke();
        g.lineWidth = 2; g.strokeStyle = `rgba(${DRIVEN_BLUE}, ${(0.9 * alpha).toFixed(3)})`; g.stroke();
        if (!c.doneAt) drawCar(g, pos.x, pos.y, pos.heading);
      }

      // GPS pings: a ring that grows and fades where a car reported in at a town.
      g.lineWidth = 1.5;
      for (const r of rings) {
        const p = (now - r.born) / (PING_LIFE_S * 1000);
        g.strokeStyle = `rgba(${ACCENT_BLUE}, ${((1 - p) * (r.big ? 0.6 : 0.4)).toFixed(3)})`;
        g.beginPath(); g.arc(r.x, r.y, 4 + (r.big ? 34 : 16) * p, 0, TAU); g.stroke();
      }
    }

    function frame(now: number) {
      if (disposed) return;
      const dt = Math.min(0.05, last ? (now - last) / 1000 : 0);
      last = now;
      step(dt, now);
      draw(now);
      raf = requestAnimationFrame(frame);
    }

    const onMove = (e: PointerEvent) => {
      const r = canvas!.getBoundingClientRect();
      pointer.x = e.clientX - r.left;
      pointer.y = e.clientY - r.top;
      pointer.on = true;
    };
    const onLeave = () => { pointer.on = false; };
    const onVisibility = () => {
      if (document.hidden) { cancelAnimationFrame(raf); raf = 0; }
      else if (!raf) { last = 0; raf = requestAnimationFrame(frame); }
    };

    const ro = new ResizeObserver(resize);
    ro.observe(host);
    resize();
    if (!still) {
      // Open with a few cars already on the road rather than an empty map.
      for (let i = 0; i < 4; i++) {
        const car = startCar();
        if (car) partWay(car, (i + 1) * 0.18);
      }
      host.addEventListener('pointermove', onMove);
      host.addEventListener('pointerleave', onLeave);
      document.addEventListener('visibilitychange', onVisibility);
      raf = requestAnimationFrame(frame);
    }
    return () => {
      disposed = true;
      cancelAnimationFrame(raf);
      ro.disconnect();
      host.removeEventListener('pointermove', onMove);
      host.removeEventListener('pointerleave', onLeave);
      document.removeEventListener('visibilitychange', onVisibility);
    };
  }, []);

  return <canvas ref={canvasRef} className={className} aria-hidden="true" />;
}
